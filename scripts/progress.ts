/** Generates the progress bar at the top of TODO.md from TODO.md itself, so it cannot go stale.
 *  `npm run progress` rewrites the block; `npm run check:docs` fails when the block is out of date.
 *  Delivered tasks are deleted from TODO.md, so the scope is the fixed list of demo tasks that were open when
 *  tracking began (history) plus every task that is still open in TODO.md. A task counts as delivered once it
 *  no longer appears in TODO.md; history tasks that are still open count as remaining. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const HISTORY_SCOPE: readonly string[] = [
  ...Array.from({ length: 13 }, (_, i) => `AUTO-${String(i + 3).padStart(2, '0')}`),
  'PAY-08', 'SIM-02', 'SIM-05',
  ...Array.from({ length: 8 }, (_, i) => `QA-${String(i + 1).padStart(2, '0')}`),
  // Tasks first tracked after the start: add the ID here in the commit that closes it, or it would vanish instead of counting.
  'P2-08', 'P2-10', 'P2-12', 'P2-15', 'QA-09', 'P2-16', 'P2-07', 'P1-18', 'P2-13', 'P2-11', 'QA-10',
];
const START = '<!-- progress:start -->', END = '<!-- progress:end -->', WIDTH = 24;

export function renderProgress(todo: string): string {
  const openIds: string[] = [], steps = { done: 0, open: 0 };
  let inTask = false;
  for (const line of todo.replaceAll('\r\n', '\n').split('\n')) {
    const task = /^- \[ \] \*\*([A-Z][A-Z0-9]*-\d+)\b/.exec(line);
    if (task) { openIds.push(task[1]); inTask = true; continue; }
    const step = /^ {2}- \[([ x])\]/.exec(line);
    if (step && inTask) { if (step[1] === 'x') steps.done++; else steps.open++; continue; }
    if (!step) inTask = false;
  }
  const open = new Set(openIds);
  const scope = [...HISTORY_SCOPE, ...openIds.filter(id => !HISTORY_SCOPE.includes(id))];
  const delivered = HISTORY_SCOPE.filter(id => !open.has(id)), remaining = scope.filter(id => open.has(id));
  const filled = Math.round(WIDTH * delivered.length / scope.length);
  const percent = Math.round(100 * delivered.length / scope.length);
  const inFlight = steps.done + steps.open > 0 ? ` · sub-steps landed in open tasks: ${steps.done} of ${steps.done + steps.open}` : '';
  return [START,
    `**Progress:** \`${'█'.repeat(filled)}${'░'.repeat(WIDTH - filled)}\` **${percent}%** · ${delivered.length} of ${scope.length} tracked tasks delivered (${remaining.length} open)${inFlight}`,
    `Delivered: ${delivered.join(', ') || 'none yet'}. Open: ${remaining.join(', ') || 'none'}.`,
    `_Generated by \`npm run progress\` from this file; the check fails if it is stale._`,
    END].join('\n');
}

export function withProgress(todo: string): string {
  const eol = todo.includes('\r\n') ? '\r\n' : '\n', text = todo.replaceAll('\r\n', '\n');
  const block = renderProgress(text);
  const a = text.indexOf(START), b = text.indexOf(END);
  let out: string;
  if (a >= 0 && b > a) out = text.slice(0, a) + block + text.slice(b + END.length);
  else { const firstQuote = text.indexOf('\n> '); out = text.slice(0, text.indexOf('\n', firstQuote + 1) + 1) + '\n' + block + '\n' + text.slice(text.indexOf('\n', firstQuote + 1) + 1); }
  return eol === '\r\n' ? out.replaceAll('\n', '\r\n') : out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const before = readFileSync('TODO.md', 'utf8'), after = withProgress(before);
  if (before !== after) writeFileSync('TODO.md', after);
  console.log(renderProgress(after).split('\n').slice(1, 3).join('\n'));
}
