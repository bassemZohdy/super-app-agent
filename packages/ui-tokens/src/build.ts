/** Builds every shell's design constants from the one layered source (P2-13): primitive values, semantic roles (light and dark)
 *  and component tokens. Pure, so the drift check and the tests can run it without touching files. CSS keeps the variable
 *  names the shells already use; `tokens.json` keeps its legacy shape and gains the semantic and component layers; the Dart
 *  file gives Flutter the same colors, spacing and radii. */
export type Layered = {
  primitive: { color: Record<string, string>; font: Record<string, string>; size: Record<string, string>; weight: Record<string, string>; space: Record<string, string>; radius: Record<string, string>; shadow: Record<string, string>; breakpoint: Record<string, string> };
  semantic: { light: Record<string, string>; dark: Record<string, string> };
  component: Record<string, Record<string, string>>;
};

const REF = /^\{([A-Za-z0-9_.-]+)\}$/;

/** Resolves `{path}` references to a final value. `semantic.x` means the light role. Missing paths and cycles throw. */
export function resolveToken(source: Layered, value: string, theme: 'light' | 'dark' = 'light', seen: string[] = []): string {
  const match = REF.exec(value);
  if (!match) return value;
  const path = match[1];
  if (seen.includes(path)) throw new Error(`Token reference cycle: ${[...seen, path].join(' -> ')}`);
  const parts = path.split('.');
  let node: unknown = parts[0] === 'semantic' ? undefined : source;
  if (parts[0] === 'semantic') {
    const role = parts[1], layer = theme === 'dark' && role in source.semantic.dark ? source.semantic.dark : source.semantic.light;
    node = parts.length === 2 ? layer[role] : undefined;
  } else for (const part of parts) node = (node as Record<string, unknown> | undefined)?.[part];
  if (typeof node !== 'string') throw new Error(`Unknown token reference {${path}}`);
  return resolveToken(source, node, theme, [...seen, path]);
}

export function validateSource(source: Layered) {
  const colors = /^#[0-9a-f]{6}$/;
  for (const [name, value] of Object.entries(source.primitive.color)) if (!colors.test(value)) throw new Error(`Primitive color ${name} must be a lowercase #rrggbb value.`);
  for (const theme of ['light', 'dark'] as const) for (const [role, value] of Object.entries(source.semantic[theme])) {
    if (!REF.test(value)) throw new Error(`Semantic ${theme}.${role} must reference a primitive, not repeat a value.`);
    if (!colors.test(resolveToken(source, value, theme))) throw new Error(`Semantic ${theme}.${role} does not resolve to a color.`);
  }
  for (const role of Object.keys(source.semantic.dark)) if (!(role in source.semantic.light)) throw new Error(`Dark role ${role} has no light role.`);
  for (const [component, tokens] of Object.entries(source.component)) for (const [name, value] of Object.entries(tokens)) {
    if (!REF.test(value)) throw new Error(`Component ${component}.${name} must reference a token, not repeat a value.`);
    resolveToken(source, value);
  }
}

const kebab = (name: string) => name.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
const cssVar = (group: string, name: string) => `--${group}-${kebab(name)}`;
const dartName = (name: string) => name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const dartColor = (hex: string) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const px = (value: string) => Number.parseFloat(value);
const lines = (entries: string[]) => entries.join('\n');

export function buildThemeCss(source: Layered): string {
  const p = source.primitive, role = (r: string) => resolveToken(source, source.semantic.light[r]);
  const roleVar = (r: string) => `var(${cssVar('color', r)})`;
  const component = Object.entries(source.component).flatMap(([name, tokens]) => Object.entries(tokens).map(([token, value]) => {
    const ref = REF.exec(value)![1].split('.');
    // A component follows the active theme through its semantic role; a primitive reference is a fixed value.
    return `  ${cssVar(name, token)}: ${ref[0] === 'semantic' ? roleVar(ref[1]) : resolveToken(source, value)};`;
  }));
  return lines([
    '/* Generated by npm run tokens:generate from tokens.source.json. Do not edit. */',
    ':root {',
    '  /* Primitive colors */',
    ...Object.entries(p.color).map(([name, value]) => `  --primitive-color-${name}: ${value};`),
    '',
    '  /* Colors (semantic roles) */',
    ...Object.keys(source.semantic.light).map(r => `  ${cssVar('color', r)}: ${role(r)};`),
    '',
    '  /* Typography */',
    `  --font-family-base: ${p.font.base};`,
    `  --font-family-mono: ${p.font.mono};`,
    ...Object.entries(p.size).map(([name, value]) => `  --font-size-${name}: ${value};`),
    '',
    '  /* Spacing */',
    ...Object.entries(p.space).map(([name, value]) => `  --spacing-${name}: ${value};`),
    '',
    '  /* Radii */',
    ...Object.entries(p.radius).map(([name, value]) => `  --radius-${name}: ${value};`),
    '',
    '  /* Shadows */',
    ...Object.entries(p.shadow).map(([name, value]) => `  --shadow-${name}: ${value};`),
    '',
    '  /* Components */',
    ...component,
    '}',
    '',
    "[data-theme='dark'] {",
    ...Object.keys(source.semantic.dark).map(r => `  ${cssVar('color', r)}: ${resolveToken(source, source.semantic.dark[r], 'dark')};`),
    '}',
    '',
  ]);
}

/** The legacy flat shape the `UI_TOKENS` import exposes, plus the semantic and component layers resolved to values. */
export function buildTokensJson(source: Layered): string {
  const p = source.primitive, resolved = (layer: Record<string, string>, theme: 'light' | 'dark') => Object.fromEntries(Object.entries(layer).map(([k, v]) => [k, resolveToken(source, v, theme)]));
  const colors = resolved(source.semantic.light, 'light');
  return `${JSON.stringify({
    colors,
    typography: { fontFamily: p.font.base.replace(/"/g, ''), fontMono: p.font.mono, sizes: p.size, weights: p.weight },
    spacing: p.space, radii: p.radius, shadows: p.shadow, breakpoints: p.breakpoint,
    colorsDark: resolved(source.semantic.dark, 'dark'),
    components: Object.fromEntries(Object.entries(source.component).map(([name, tokens]) => [name, resolved(tokens, 'light')])),
  }, null, 2)}\n`;
}

export function buildDart(source: Layered): string {
  const p = source.primitive;
  return lines([
    '// Generated by npm run tokens:generate from packages/ui-tokens/src/tokens.source.json. Do not edit.',
    "import 'dart:ui' show Color;",
    '',
    '/// Design constants shared with the React and Angular shells.',
    'abstract final class CitysideTokens {',
    ...Object.keys(source.semantic.light).map(r => `  static const Color ${r} = ${dartColor(resolveToken(source, source.semantic.light[r]))};`),
    ...Object.keys(source.semantic.dark).map(r => `  static const Color dark${r[0].toUpperCase()}${r.slice(1)} = ${dartColor(resolveToken(source, source.semantic.dark[r], 'dark'))};`),
    ...Object.entries(p.space).map(([name, value]) => `  static const double space${dartName(`-${name}`)} = ${px(value).toFixed(1)};`),
    ...Object.entries(p.radius).filter(([, value]) => px(value) < 1000).map(([name, value]) => `  static const double radius${dartName(`-${name}`)} = ${px(value).toFixed(1)};`),
    '}',
    '',
  ]);
}

export const outputs = (source: Layered) => ({
  'packages/ui-tokens/src/theme.css': buildThemeCss(source),
  'packages/ui-tokens/src/tokens.json': buildTokensJson(source),
  'apps/shell-flutter/lib/theme/tokens.g.dart': buildDart(source),
});
